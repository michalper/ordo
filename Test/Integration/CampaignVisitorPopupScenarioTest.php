        self::assertNull($popup->getCouponCode(), 'a tier with no coupon_rule_id must never mint a coupon');
    }

    /**
     * Proves the real weighted-random pick (Model\Campaign\RewardTierSelector, through the real
     * "popup" action, through a real dispatch each time) actually lands in each tier roughly
     * proportionally to its weight, against real ordo_pending_popup rows - not a mocked
     * selector. A fresh visitor_id per dispatch, rather than one visitor dispatched repeatedly,
     * is what makes that repetition possible at all: ShowPopup's own frequency cap (default 24h)
     * would otherwise suppress every dispatch after the first for the same visitor.
     */
    public function testPopupActionRewardTierSelectionDistributesAcrossManyDispatchesRoughlyByWeight(): void
    {
        $visitorIdPrefix = 'itest-wheel-' . uniqid('', true) . '-';
        $this->cleanupVisitorIdPrefix = $visitorIdPrefix;

        $campaignId = $this->createCampaign('visitor_tag_added');
        $this->addAction($campaignId, 'popup', [
            'headline' => 'Spin to win!',
            'reward_tiers' => [
                ['label' => 'tier-a', 'weight' => 50],
                ['label' => 'tier-b', 'weight' => 50],
            ],
        ]);
        $this->cache->clean([CampaignDispatcher::CACHE_TAG]);

        $trials = 60;
        for ($i = 0; $i < $trials; $i++) {
            $this->dispatcher->dispatch(
                'visitor_tag_added',
                ['visitor_id' => $visitorIdPrefix . $i, 'tag' => 'irrelevant']
            );
        }

        $collectionFactory = self::$objectManager->get(PendingPopupCollectionFactory::class);

        $all = $collectionFactory->create();
        $all->addFieldToFilter('visitor_id', ['like' => $visitorIdPrefix . '%']);
        self::assertSame($trials, $all->getSize(), 'every one of the 60 dispatches must have queued a real row');

        $tierA = $collectionFactory->create();
        $tierA->addFieldToFilter('visitor_id', ['like' => $visitorIdPrefix . '%'])
            ->addFieldToFilter('reward_label', 'tier-a');
        $countA = $tierA->getSize();

        $tierB = $collectionFactory->create();
        $tierB->addFieldToFilter('visitor_id', ['like' => $visitorIdPrefix . '%'])
            ->addFieldToFilter('reward_label', 'tier-b');
        $countB = $tierB->getSize();

        self::assertSame($trials, $countA + $countB, 'every row must have landed in exactly one of the two tiers');
        // 50/50 over 60 real random dispatches - binomial std dev is ~3.9, so 10 is roughly 5
        // standard deviations below the mean of 30: this would only fail if the real weighted
        // selection weren't actually random/weighted correctly, not from ordinary run-to-run noise.
        self::assertGreaterThan(10, $countA);
        self::assertGreaterThan(10, $countB);
    }
