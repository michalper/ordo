<?php
declare(strict_types=1);

namespace Ordo\Automation\Model;

use Magento\Framework\App\ResourceConnection;
use Magento\Framework\Math\Random;
use Magento\SalesRule\Helper\Coupon as CouponHelper;
use Magento\SalesRule\Model\CouponFactory;
use Magento\SalesRule\Model\ResourceModel\Coupon as CouponResource;
use Psr\Log\LoggerInterface;

/**
 * Generates a single-use coupon code tied to an existing SalesRule (the admin creates the
 * discount rule once — e.g. "10% off", coupon type "Specific Coupon" — and this just mints
 * a fresh code against it per customer/event, instead of every customer sharing one code).
 */
class CouponGenerator
{
    public function __construct(
        private readonly CouponFactory $couponFactory,
        private readonly CouponResource $couponResource,
        private readonly Random $random,
        private readonly ResourceConnection $resourceConnection,
        private readonly LoggerInterface $logger
    ) {
    }

    /**
     * $campaignId, when given (Model\Campaign\Action\GenerateCoupon passes its own context's
     * campaign_id), is logged to ordo_coupon_campaign_log so Model\ResourceModel\RevenueAnalytics\
     * Grid\Collection can later show which campaign generated a coupon that was actually used -
     * see docs/adr/0028. Logging failure is swallowed (logged, not thrown): losing the
     * attribution row must never cost the merchant the coupon code itself, which by this point
     * has already been minted and saved.
     */
    public function generate(int $ruleId, string $prefix = 'ORDO', int $usageLimit = 1, ?int $campaignId = null): string
    {
        $code = $prefix . '-' . strtoupper($this->random->getRandomString(10));

        $coupon = $this->couponFactory->create();
        $coupon->setRuleId($ruleId);
        $coupon->setCode($code);
        // salesrule_coupon.type is its OWN enum, unrelated to Rule::COUPON_TYPE_* (the rule's
        // coupon *mode* — No Coupon/Specific/Auto — a completely different column on a
        // different table). Confirmed against Magento\SalesRule\Model\Coupon\Massgenerator
        // (the core code that actually populates this same "Manage Coupon Codes" grid): it uses
        // Helper\Coupon::COUPON_TYPE_SPECIFIC_AUTOGENERATED (1), which is also exactly what
        // Collection::addGeneratedCouponsFilter() filters on (addFieldToFilter('type', '1')).
        // This module previously used Rule::COUPON_TYPE_SPECIFIC (2) here by mistake — the coupon
        // still saved without error, but silently failed that filter too (on top of the
        // is_primary mismatch fixed alongside this), so it never appeared in the grid.
        $coupon->setType(CouponHelper::COUPON_TYPE_SPECIFIC_AUTOGENERATED);
        $coupon->setUsageLimit($usageLimit);
        $coupon->setUsagePerCustomer(1);
        // Deliberately NOT calling setIsPrimary() at all — leave the column NULL. The admin's
        // own "Manage Coupon Codes" grid (Magento\SalesRule\Model\ResourceModel\Coupon\
        // Collection::addGeneratedCouponsFilter()) filters is_primary with an explicit
        // ['null' => 1] condition, not "is_primary = 0" — a coupon saved with is_primary=false
        // (which persists as 0, not NULL) is silently excluded from that query. Confirmed via a
        // real CI run: the coupon generates successfully every time (logged, code returned) but
        // never appeared in the grid even after a full 60s poll, with salesrule_coupon
        // unreachable post-hoc since the test's own cleanup deletes the rule (cascades its
        // coupons) before any diagnostic dump could run — this filter mismatch is the actual
        // root cause, not a display/timing race.

        $this->couponResource->save($coupon);

        if ($campaignId !== null) {
            $this->logCampaignAttribution((int) $coupon->getId(), $campaignId);
        }

        return $code;
    }

    private function logCampaignAttribution(int $couponId, int $campaignId): void
    {
        try {
            $connection = $this->resourceConnection->getConnection();
            $connection->insert($this->resourceConnection->getTableName('ordo_coupon_campaign_log'), [
                'coupon_id' => $couponId,
                'campaign_id' => $campaignId,
            ]);
        } catch (\Throwable $e) {
            $this->logger->error(sprintf(
                'Ordo_Automation: failed to log coupon #%d as generated by campaign #%d: %s',
                $couponId,
                $campaignId,
                $e->getMessage()
            ));
        }
    }
}
